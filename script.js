/* =========================================
   LANGUAGE SWITCHER
========================================= */

const languageButtons =
    document.querySelectorAll(".language-btn");


function changeLanguage(language) {

    const data = translations[language];

    if (!data) {
        return;
    }


    document
        .querySelectorAll("[data-i18n]")
        .forEach(function (element) {

            const key =
                element.dataset.i18n;


            if (!data[key]) {
                return;
            }


            /*
                Hero title contains HTML:
                <br> and <span>
            */

            if (key === "heroTitle") {

                element.innerHTML =
                    data[key];

            }

            else {

                element.textContent =
                    data[key];

            }

        });


    /* Update active language button */

    languageButtons.forEach(
        function (button) {

            button.classList.remove(
                "active"
            );

        }
    );


    const activeButton =
        document.querySelector(
            `[data-language="${language}"]`
        );


    if (activeButton) {

        activeButton.classList.add(
            "active"
        );

    }


    document.documentElement.lang =
        language;


    /* Save selected language */

    localStorage.setItem(
        "jasmineLanguage",
        language
    );
}



/* =========================================
   LANGUAGE BUTTON EVENTS
========================================= */

languageButtons.forEach(
    function (button) {

        button.addEventListener(
            "click",
            function () {

                const language =
                    button.dataset.language;

                changeLanguage(
                    language
                );

            }
        );

    }
);



/* =========================================
   CONTACT FORM
========================================= */

const lessonForm =
    document.getElementById(
        "lessonForm"
    );


const messageResult =
    document.getElementById(
        "messageResult"
    );


const generatedMessage =
    document.getElementById(
        "generatedMessage"
    );


const copyMessageButton =
    document.getElementById(
        "copyMessage"
    );



if (lessonForm) {

    lessonForm.addEventListener(
        "submit",
        function (event) {

            event.preventDefault();


            const name =
                document
                    .getElementById(
                        "studentName"
                    )
                    .value
                    .trim();


            const subject =
                document
                    .getElementById(
                        "studentSubject"
                    )
                    .value;


            const level =
                document
                    .getElementById(
                        "studentLevel"
                    )
                    .value;


            const time =
                document
                    .getElementById(
                        "studentTime"
                    )
                    .value
                    .trim();


            let message =
                `Hi Jasmine! My name is ${name}. ` +
                `I'm interested in studying ${subject}. ` +
                `My current level is ${level}.`;


            if (time) {

                message +=
                    ` My preferred lesson time is ${time} Vietnam time.`;

            }


            message +=
                " Could you please let me know if this time is available?";


            generatedMessage.textContent =
                message;


            messageResult.hidden =
                false;


            messageResult.scrollIntoView({
                behavior: "smooth",
                block: "nearest"
            });

        }
    );

}



/* =========================================
   COPY REGISTRATION MESSAGE
========================================= */

if (copyMessageButton) {

    copyMessageButton.addEventListener(
        "click",
        async function () {

            const text =
                generatedMessage.textContent;


            if (!text) {
                return;
            }


            try {

                await navigator.clipboard.writeText(
                    text
                );


                const originalText =
                    copyMessageButton.textContent;


                copyMessageButton.textContent =
                    "Copied ✓";


                setTimeout(
                    function () {

                        copyMessageButton.textContent =
                            originalText;

                    },
                    1500
                );

            }

            catch (error) {

                /*
                    Fallback for browsers where
                    clipboard API is unavailable.
                */

                const textArea =
                    document.createElement(
                        "textarea"
                    );


                textArea.value =
                    text;


                document.body.appendChild(
                    textArea
                );


                textArea.select();


                document.execCommand(
                    "copy"
                );


                textArea.remove();


                const originalText =
                    copyMessageButton.textContent;


                copyMessageButton.textContent =
                    "Copied ✓";


                setTimeout(
                    function () {

                        copyMessageButton.textContent =
                            originalText;

                    },
                    1500
                );

            }

        }
    );

}



/* =========================================
   SMOOTH SCROLL
   HOMEPAGE INTERNAL LINKS ONLY
========================================= */

document
    .querySelectorAll('a[href^="#"]')
    .forEach(function (link) {

        link.addEventListener(
            "click",
            function (event) {

                const targetId =
                    link.getAttribute(
                        "href"
                    );


                if (
                    !targetId ||
                    targetId === "#"
                ) {
                    return;
                }


                const target =
                    document.querySelector(
                        targetId
                    );


                if (!target) {
                    return;
                }


                event.preventDefault();


                target.scrollIntoView({
                    behavior: "smooth",
                    block: "start"
                });

            }
        );

    });



